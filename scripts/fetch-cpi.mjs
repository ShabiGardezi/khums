#!/usr/bin/env node
/**
 * Decision 83: refreshes the monthly consumer price index data the staff calculator uses to
 * pre-fill inflation figures (`apps/api/src/inflation/cpi-data.ts`).
 *
 * Source: International Monetary Fund, Consumer Price Index (CPI) dataset (IMF.STA:CPI), the
 * all-items headline index of each economy, monthly ("<economy>.CPI._T.IX.M"); the euro uses the
 * euro-area Harmonised Index of Consumer Prices ("G163.HICP._T.IX.M"). The IMF compiles these from
 * national authorities, the OECD and Eurostat. Values are copied exactly as published (strings);
 * a month the IMF does not publish is stored as missing, never filled in.
 *
 * Usage: node scripts/fetch-cpi.mjs   (network access to api.imf.org required)
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../apps/api/src/inflation/cpi-data.ts');
const API = 'https://api.imf.org/external/sdmx/2.1/data/IMF.STA,CPI';
const START = '1980-01';

/** Each supported currency → the economy whose index measures it (ISO 3166 alpha-3; G163 = euro area). */
const ECONOMIES = {
  AED: 'ARE',
  AFN: 'AFG',
  AUD: 'AUS',
  AZN: 'AZE',
  BDT: 'BGD',
  BHD: 'BHR',
  CAD: 'CAN',
  CHF: 'CHE',
  EUR: 'G163',
  GBP: 'GBR',
  INR: 'IND',
  IQD: 'IRQ',
  IRR: 'IRN',
  JOD: 'JOR',
  JPY: 'JPN',
  KES: 'KEN',
  KWD: 'KWT',
  LBP: 'LBN',
  NOK: 'NOR',
  NZD: 'NZL',
  OMR: 'OMN',
  PKR: 'PAK',
  QAR: 'QAT',
  SAR: 'SAU',
  SEK: 'SWE',
  SYP: 'SYR',
  TRY: 'TUR',
  TZS: 'TZA',
  USD: 'USA',
  YER: 'YEM',
  ZAR: 'ZAF',
};

const monthIndex = (ym) => {
  const [y, m] = ym.split('-').map(Number);
  return y * 12 + (m - 1);
};
const ymOf = (i) => `${String(Math.floor(i / 12))}-${String((i % 12) + 1).padStart(2, '0')}`;

async function series(economy) {
  const index = economy === 'G163' ? 'HICP' : 'CPI';
  const url = `${API}/${economy}.${index}._T.IX.M?startPeriod=${START}&detail=dataonly`;
  const response = await fetch(url, {
    headers: { accept: 'application/vnd.sdmx.data+csv;version=1.0.0' },
  });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`${economy}: HTTP ${String(response.status)}`);
  const lines = (await response.text())
    .split('\n')
    .slice(1)
    .filter((l) => l.trim() !== '');
  const points = new Map();
  for (const line of lines) {
    const cells = line.split(',');
    const period = cells[6]; // e.g. 2023-M01
    const value = cells[7];
    if (!/^\d{4}-M\d{2}$/.test(period) || !/^\d+(\.\d+)?$/.test(value)) continue;
    points.set(monthIndex(period.replace('-M', '-')), value);
  }
  if (points.size === 0) return null;
  const first = Math.min(...points.keys());
  const last = Math.max(...points.keys());
  const values = [];
  for (let i = first; i <= last; i += 1) values.push(points.get(i) ?? '-');
  return { economy, index, start: ymOf(first), values: values.join(' ') };
}

const out = {};
for (const [currency, economy] of Object.entries(ECONOMIES)) {
  const s = await series(economy);
  if (s === null) {
    console.log(`${currency} (${economy}): no monthly series`);
    continue;
  }
  out[currency] = s;
  console.log(`${currency} (${economy}): ${s.start}, ${String(s.values.split(' ').length)} months`);
}

const retrieved = new Date().toISOString().slice(0, 10);
const body = Object.entries(out)
  .map(
    ([c, s]) =>
      `  ${c}: {\n    economy: '${s.economy}',\n    index: '${s.index}',\n    start: '${s.start}',\n    values:\n      '${s.values}',\n  },`,
  )
  .join('\n');
writeFileSync(
  OUT,
  `// GENERATED by scripts/fetch-cpi.mjs — do not edit by hand (decision 83).
// Source: International Monetary Fund, Consumer Price Index (CPI) dataset, IMF.STA:CPI
// (https://data.imf.org/en/datasets/IMF.STA:CPI): all-items index, monthly; the euro uses the
// euro-area HICP. Compiled by the IMF from national authorities, the OECD and Eurostat.
// Values are exactly as published; "-" marks a month that was not published (never filled in).
import type { CpiSeries } from '@khums/core';

export const CPI_SOURCE =
  'International Monetary Fund, Consumer Price Index (CPI) dataset (IMF.STA:CPI), retrieved ${retrieved}';

export const CPI_SERIES: Readonly<Record<string, CpiSeries>> = {
${body}
};
`,
);
console.log(`wrote ${OUT}`);
